"""Copy the exact existing JMA2001 samples into Rust; do not fit or round."""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parents[1]
source = root / 'lib/core/source_estimation/kanameishi_jma2001_travel_time_table.dart'
raw = source.read_bytes()
text = raw.decode('utf-8')
out = ['// Generated by tools/generate_rust_hyp_tables.py from the existing Dart source.',
       '// Source SHA256: ' + hashlib.sha256(raw).hexdigest()]
for name, rust in [('_depths', 'DEPTHS'), ('_distances', 'DISTANCES'), ('_pTimes', 'P_TIMES'), ('_sTimes', 'S_TIMES')]:
    match = re.search(r'const ' + name + r' = <double>\[(.*?)\];', text, re.S)
    if match is None:
        raise ValueError('Missing original array: ' + name)
    values = [v.strip() for v in match[1].split(',') if v.strip()]
    if any(not re.fullmatch(r'-?\d+(?:\.\d+)?(?:e[+-]?\d+)?', v, re.I) for v in values):
        raise ValueError('Unexpected original numeric literal')
    rust_values = [v if '.' in v or 'e' in v.lower() else v + '.0' for v in values]
    out.append(f'pub const {rust}: [f64; {len(values)}] = [\n' + '\n'.join(', '.join(rust_values[i:i+12]) + ',' for i in range(0, len(values), 12)) + '\n];')
(root / 'native/station_core/src/hyp_travel_tables.rs').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
