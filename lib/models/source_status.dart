/// 数据源连接状态枚举
///
/// 定义了数据源服务可能处于的连接状态。
/// 用于在 UI 中显示各数据源的连接状态指示灯。

/// 数据源状态
enum SourceStatus {
  /// 已连接
  ///
  /// 数据源已成功建立连接，正在正常接收数据。
  connected,

  /// 已断开
  ///
  /// 数据源连接已断开，未在尝试重连。
  disconnected,

  /// 连接错误
  ///
  /// 数据源连接过程中发生错误。
  /// 通常会触发自动重连机制。
  error,

  /// 同步中
  ///
  /// 数据源正在同步数据，如获取历史记录或测站列表。
  synchronizing,

  /// 连接中
  ///
  /// 数据源正在尝试建立连接。
  connecting
}
